def find_pdf(paper):
    """Locate the downloaded PDF associated with a paper."""

    existing_path = paper.get("pdf_path")

    if existing_path and os.path.isfile(existing_path):
        return existing_path

    filename = create_filename(
        paper.get("title") or "Untitled"
    )

    candidate = os.path.join("data", "papers", filename)

    if os.path.isfile(candidate):
        return candidate

    return None


def retrieve_paper_evidence(paper, retriever):
    """Retrieve relevant passages from one specific paper."""

    pdf_path = find_pdf(paper)

    if not pdf_path or not retriever:
        return []

    filename = os.path.basename(pdf_path)

    queries = [
        f"{paper.get('title')}. Research objective, context, "
        "study design, participants and sample.",

        f"{paper.get('title')}. Recommendation techniques, "
        "explainability methods and datasets.",

        f"{paper.get('title')}. Evaluation metrics, results, "
        "main findings and limitations."
    ]

    passages = {}
    
    for query in queries:

        results = retriever.search(
            query,
            top_k=4,
            source_pdf=filename
        )

        for result in results:

            key = (
                result["source_pdf"],
                result["page_number"],
                result["chunk_index"]
            )

            passages[key] = result

    return list(passages.values())



def extract_paper_information(paper, retriever=None, protocol=None):

    passages = retrieve_paper_evidence(
        paper,
        retriever
    )

    if passages:
        evidence_text = []

        for passage in passages:
            evidence_text.append(
                f"[SOURCE: {passage['source_pdf']} | "
                f"PAGE: {passage['page_number']}]\n"
                f"{passage['text']}"
            )

        full_text_evidence = "\n\n".join(evidence_text)
        extraction_source = "full_text_rag"

    else:
        full_text_evidence = "No full-text passages available."
        extraction_source = "abstract"

    dimensions = (protocol or {}).get(
        "extraction_dimensions", []
    )

    result = extraction_chain.invoke({
        "title": paper.get("title") or "Unavailable",
        "abstract": (paper.get("abstract") or "Unavailable")[:5000],
        "extraction_dimensions": "\n".join(
            f"- {dimension}" for dimension in dimensions
        ) or "No topic-specific dimensions provided.",
        "full_text_evidence": full_text_evidence,
        "extraction_source": extraction_source
    })

    return {
        **paper,
        "extracted_information": result,
        "extraction_source": extraction_source,
        "evidence_count": len(result.get("evidence", []))
    }


def prepare_full_text_documents(state):
    """Retrieve PDFs, extract their text, and update the RAG index."""

    print("\n[PDF Preparation] Starting full-text preparation...")

    papers = state.get("included_papers", [])
    prepared_papers = []
    full_text_available = []

    if not papers:
        return {
            "pdf_retrieval_results": [],
            "full_text_available_papers": [],
            "current_stage": "pdf_retrieval_skipped",
            "execution_logs": state.get("execution_logs", []) + [
                "PDF preparation skipped: no papers passed title/abstract screening."
            ]
        }

    # 1. Retrieve PDFs
    print("\n[PDF Preparation] Retrieving PDFs...")
    prepared_papers = retrieve_pdfs(papers)

    # 2. Extract PDF text
    print("\n[PDF Preparation] Extracting PDF text...")

    for paper in prepared_papers:

        paper["pdf_text_processed"] = False

        if not paper.get("pdf_path"):
            continue

        try:
            process_pdf(paper["pdf_path"])
            paper["pdf_text_processed"] = True
            full_text_available.append(paper)

        except Exception as error:
            paper["pdf_text_error"] = str(error)

            print(
                f"[PDF Preparation] Text extraction failed for "
                f"{paper.get('title')}: {error}"
            )

    # 3. Update the RAG index
    print("\n[PDF Preparation] Updating RAG index...")

    try:
        indexed_chunks = build_index()
        print("[PDF Preparation] Indexed chunks:", indexed_chunks)

    except Exception as error:
        indexed_chunks = 0
        print("[PDF Preparation] RAG indexing failed:", error)

    retrieved_count = sum(
        1 for paper in prepared_papers
        if paper.get("pdf_path")
    )

    print("\n[PDF Preparation] Preparation completed.")
    print("Papers sought:", len(papers))
    print("PDFs retrieved:", retrieved_count)
    print("PDFs processed:", len(full_text_available))

    return {
        "pdf_retrieval_results": prepared_papers,
        "full_text_available_papers": full_text_available,
        "current_stage": "full_text_prepared",
        "execution_logs": state.get("execution_logs", []) + [
            f"PDFs sought for retrieval: {len(papers)}.",
            f"PDFs retrieved: {retrieved_count}.",
            f"PDFs successfully processed: {len(full_text_available)}.",
            f"RAG index updated with {indexed_chunks} new chunks."
        ]
    }


def run_extraction_agent(state):
    """Extract information only from papers eligible after full-text assessment."""

    print("\n[Extraction Agent] Starting information extraction...")

    papers = state.get("full_text_eligible_papers", [])
    protocol = state.get("protocol", {})
    extracted_data = []

    if not papers:
        print("[Extraction Agent] No papers passed full-text eligibility.")

        return {
            "extracted_data": [],
            "current_stage": "extraction_skipped",
            "execution_logs": state.get("execution_logs", []) + [
                "Extraction skipped: no papers passed full-text eligibility."
            ]
        }

    # Initialize the RAG retriever once.
    retriever = None

    try:
        if os.path.isdir("data/chroma_db"):
            retriever = PaperRetriever()
            print("[Extraction Agent] RAG retriever initialized.")

    except Exception as error:
        print("[Extraction Agent] RAG initialization failed:", error)

    full_text_count = 0
    abstract_count = 0

    for index, paper in enumerate(papers, 1):

        print(
            f"\n[Extraction Agent] Processing paper "
            f"{index}/{len(papers)}..."
        )

        try:
            extracted = extract_paper_information(
                paper,
                retriever,
                protocol=protocol
            )

            extracted_data.append(extracted)

            if extracted["extraction_source"] == "full_text_rag":
                full_text_count += 1
            else:
                abstract_count += 1

            print("[Extraction Agent] Source:", extracted["extraction_source"])
            print("[Extraction Agent] Evidence entries:", extracted["evidence_count"])

        except Exception as error:
            print(
                f"[Extraction Agent] Error processing "
                f"{paper.get('title')}: {error}"
            )

    print("\n[Extraction Agent] Extraction completed.")
    print("Successfully extracted:", len(extracted_data))
    print("Full-text extraction:", full_text_count)
    print("Abstract-based extraction:", abstract_count)

    return {
        "extracted_data": extracted_data,
        "current_stage": "extraction_completed",
        "execution_logs": state.get("execution_logs", []) + [
            f"Extracted information from {len(extracted_data)} eligible papers.",
            f"Full-text extraction: {full_text_count}.",
            f"Abstract-based extraction: {abstract_count}."
        ]
    }