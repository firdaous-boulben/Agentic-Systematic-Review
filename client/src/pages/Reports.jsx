
import { useEffect, useMemo, useState } from 'react';
import { useNavigate } from 'react-router-dom';

const statusLabels = {
  queued: 'Queued',
  running: 'In Progress',
  awaiting_human_review: 'Awaiting Review',
  completed: 'Completed',
  failed: 'Failed',
};

function formatDate(date) {
  if (!date) return 'Date unavailable';

  return new Date(date).toLocaleDateString(undefined, {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });
}

function Reports() {
  const navigate = useNavigate();

  const [reviews, setReviews] = useState([]);
  const [search, setSearch] = useState('');
  const [statusFilter, setStatusFilter] = useState('all');
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  useEffect(() => {
    const fetchReviews = async () => {
      try {
        const response = await fetch('/api/reviews/');

        if (!response.ok) {
          throw new Error('Failed to load reports.');
        }

        const data = await response.json();
        setReviews(data);
      } catch (err) {
        setError(err.message || 'Something went wrong.');
      } finally {
        setLoading(false);
      }
    };

    fetchReviews();
  }, []);

  const reports = useMemo(
    () => reviews.filter((review) => review.report_available),
    [reviews]
  );

  const filteredReports = useMemo(() => {
    return reports.filter((report) => {
      const matchesSearch = report.topic
        ?.toLowerCase()
        .includes(search.toLowerCase());

      const matchesStatus =
        statusFilter === 'all' || report.status === statusFilter;

      return matchesSearch && matchesStatus;
    });
  }, [reports, search, statusFilter]);

  const completedReports = reports.filter(
    (report) => report.status === 'completed'
  ).length;

  const openReport = (reviewId) => {
    navigate(`/reviews/${reviewId}?section=report`);
  };

  if (loading) {
    return (
      <div className="reports-page">
        <div className="reports-loading">Loading reports...</div>
      </div>
    );
  }

  return (
    <div className="reports-page">
      <div className="reports-header">
        <div>
          <h1>Reports</h1>
          <p>Access the reports generated by your systematic reviews.</p>
        </div>
      </div>

      {error && (
        <div className="reports-error">
          {error}
        </div>
      )}

      <div className="reports-overview">
        <div className="reports-stat">
          <span className="reports-stat-label">Generated Reports</span>
          <strong>{reports.length}</strong>
        </div>

        <div className="reports-stat">
          <span className="reports-stat-label">Completed Reviews</span>
          <strong>{completedReports}</strong>
        </div>

        <div className="reports-stat">
          <span className="reports-stat-label">Reviews Without Reports</span>
          <strong>{reviews.length - reports.length}</strong>
        </div>
      </div>

      <div className="reports-toolbar">
        <div className="reports-search">
          <i className="bi bi-search"></i>
          <input
            type="text"
            placeholder="Search reports..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
          />
        </div>

        <select
          value={statusFilter}
          onChange={(e) => setStatusFilter(e.target.value)}
          aria-label="Filter reports by status"
        >
          <option value="all">All statuses</option>
          <option value="completed">Completed</option>
          <option value="running">In Progress</option>
          <option value="queued">Queued</option>
          <option value="awaiting_human_review">Awaiting Review</option>
          <option value="failed">Failed</option>
        </select>
      </div>

      {filteredReports.length === 0 ? (
        <div className="reports-empty">
          <i className="bi bi-file-earmark-text"></i>
          <h3>
            {reports.length === 0
              ? 'No reports generated yet'
              : 'No matching reports'}
          </h3>
          <p>
            {reports.length === 0
              ? 'Reports will appear here once a review has generated its final report.'
              : 'Try changing your search or status filter.'}
          </p>
        </div>
      ) : (
        <div className="reports-grid">
          {filteredReports.map((report) => (
            <div className="report-card" key={report.id}>
              <div className="report-card-header">
                <div className="report-icon">
                  <i className="bi bi-file-earmark-text"></i>
                </div>

                <span
                  className={`report-status status-${report.status}`}
                >
                  {statusLabels[report.status] || report.status}
                </span>
              </div>

              <div className="report-card-content">
                <h3>{report.topic || 'Untitled Review'}</h3>

                <div className="report-metadata">
                  <span>
                    <i className="bi bi-calendar3"></i>
                    Created {formatDate(report.created_at)}
                  </span>

                  <span>
                    <i className="bi bi-journals"></i>
                    {report.papers} papers
                  </span>
                </div>
              </div>

              <div className="report-card-footer">
                <button
                  type="button"
                  onClick={() => openReport(report.id)}
                >
                  Open Report
                  <i className="bi bi-arrow-right"></i>
                </button>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}

export default Reports;
